/**
 * Куда МОЖНО зачислить ученика.
 *
 * Курс-шаблон — каркас, из которого делают классы; учеников в нём быть не
 * может. Списки выбора курса живут в четырёх местах (окно распределения на
 * странице учеников и в профиле ученика, зачисление, приглашение в группу), и
 * правило у них обязано быть одно: разъедутся — дыра вернётся ровно так же,
 * как вернулась в админском окне.
 *
 * Отбор по ПОЛЮ `is_template`, а не по названию. На проде есть курс «Физика
 * ЕГЭ Шаблон -Ярослав» с `is_template = false` — это настоящий класс, и
 * фильтр по слову «Шаблон» спрятал бы его от преподавателя.
 *
 * Это только показ. Сам запрет держит база: триггер на вставку в
 * `group_students` отклоняет зачисление в шаблон независимо от интерфейса.
 */

/** Минимум, который нужен от группы, чтобы решить, годится ли она. */
export interface EnrollmentTargetGroup {
  course_id?: string | null
  courses?: { is_template?: boolean | null } | null
}

/** Группа принадлежит курсу-шаблону — зачислять в неё нельзя. */
export function isTemplateGroup(group: EnrollmentTargetGroup): boolean {
  return group.courses?.is_template === true
}

/**
 * Оставляет только те группы, куда зачисление вообще осмысленно.
 *
 * Группы без курса НЕ выбрасываются: они попадают в списки с пометкой
 * «Сначала назначьте курс» — это подсказка к действию, а не мусор.
 */
export function enrollableGroups<T extends EnrollmentTargetGroup>(groups: T[]): T[] {
  return groups.filter(group => !isTemplateGroup(group))
}
