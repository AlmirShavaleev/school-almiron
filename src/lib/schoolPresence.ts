/**
 * Присутствие в школе: кто сейчас на платформе.
 *
 * ЭТО ВТОРАЯ ВЕРСИЯ МЕХАНИЗМА. Первая (§148) делала присутствие на Supabase
 * Presence — все вошедшие отмечались в канале, читать его разрешалось только
 * админу. На превью выяснилось, что так нельзя: **чтобы отметиться в канале,
 * клиенту нужно право читать его**. Подписка проверяется на входе, и ученик до
 * `track()` не доходил вовсе, а браузер повторял попытку каждые 7–10 секунд.
 * Открыть чтение канала всем — значит показать любому ученику список тех, кто
 * сейчас онлайн (пусть идентификаторами, без имён); владелец этого не захотел.
 *
 * Поэтому теперь: **ученик пишет отметку, список читает только админ.** Две
 * definer-функции, никакого канала. Утечки нет вовсе, потому что читать
 * нечего.
 *
 * В отметке — только `profile_id`, роль и время. Ни адреса страницы, ни
 * идентификатора темы: «на каком экране находится ребёнок» владелец запретил
 * показывать, и этого нет в данных, а не спрятано на экране. Истории тоже нет:
 * строка на человека одна и затирается.
 */

/** Как часто человек отмечается. Только при видимой вкладке. */
export const PRESENCE_TOUCH_MS = 20_000

/**
 * Сколько секунд отметка считается свежей.
 *
 * 45 при отметке раз в 20: один потерянный удар не выкидывает человека из
 * списка, а закрытая вкладка пропадает за 45 секунд. Во вводной стояло «в
 * течение полуминуты» — честная цифра теперь 45 секунд, и экран так и подписан.
 */
export const PRESENCE_WINDOW_S = 45

/** Как часто панель перечитывает список. Только при видимой вкладке. */
export const PRESENCE_POLL_MS = 15_000

export interface PresencePerson {
  profileId: string
  role: string
}

/** Разбор ответа `school_presence_online()`. Битые строки отбрасываются. */
export function parseOnline(raw: unknown): PresencePerson[] {
  if (!Array.isArray(raw)) return []
  const seen = new Map<string, PresencePerson>()
  for (const row of raw) {
    const profileId = String((row as any)?.profile_id ?? '').trim()
    if (!profileId || seen.has(profileId)) continue
    seen.set(profileId, { profileId, role: String((row as any)?.role ?? '') })
  }
  return [...seen.values()]
}

/**
 * Сравнение составов. Нужно, чтобы опрос раз в 15 секунд не перерисовывал
 * список, когда в нём ничего не изменилось: у одних и тех же людей меняется
 * только `seen_at`, а он на экран не идёт.
 */
export function samePeople(a: PresencePerson[], b: PresencePerson[]): boolean {
  if (a.length !== b.length) return false
  return a.every((person, i) => person.profileId === b[i]?.profileId && person.role === b[i]?.role)
}
