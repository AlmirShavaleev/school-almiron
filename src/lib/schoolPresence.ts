/**
 * Присутствие в школе: кто сейчас на платформе.
 *
 * ЭТО ВТОРАЯ ВЕРСИЯ МЕХАНИЗМА. Первая (§148) делала присутствие на Supabase
 * Presence — все вошедшие отмечались в канале, читать его разрешалось только
 * админу. На превью выяснилось, что так нельзя: **чтобы отметиться в канале,
 * клиенту нужно право читать его**. Подписка проверяется на входе, и ученик до
 * `track()` не доходил вовсе, а браузер повторял попытку каждые 7–10 секунд.
 * Открыть чтение канала всем — значит показать любому ученику список тех, кто
 * сейчас онлайн (пусть идентификаторами, без имён); владелец этого не захотел.
 *
 * Поэтому теперь: **ученик пишет отметку, список читает только админ.** Две
 * definer-функции, никакого канала. Утечки нет вовсе, потому что читать
 * нечего.
 *
 * В отметке — только `profile_id`, роль и время. Ни адреса страницы, ни
 * идентификатора темы: «на каком экране находится ребёнок» владелец запретил
 * показывать, и этого нет в данных, а не спрятано на экране. Истории тоже нет:
 * строка на человека одна и затирается.
 *
 * ТРЕТЬЯ ПРАВКА (§165): отметки больше не привязаны к тому, видна ли вкладка.
 * Материалы открываются в новой вкладке, и прежнее правило считало ушедшим
 * того, кто как раз читает конспект. Теперь работает льготный период — см.
 * `PRESENCE_GRACE_MS` и `shouldTouch`.
 */

/** Такт отметки, когда вкладка платформы на переднем плане. */
export const PRESENCE_TOUCH_MS = 20_000

/**
 * Такт отметки, когда вкладка ушла в фон, но льготный период ещё идёт.
 *
 * Реже, чем на переднем плане: человек, читающий PDF в соседней вкладке,
 * присутствует, но обновлять его отметку так же часто незачем.
 */
export const PRESENCE_BACKGROUND_TOUCH_MS = 60_000

/**
 * Льготный период после последнего действия на платформе.
 *
 * ЗАЧЕМ ОН ВООБЩЕ. Файлы, ссылки и часть видео открываются в новой вкладке
 * (`target="_blank"`). Пока отметки шли только при видимой вкладке, ученик,
 * открывший конспект в PDF, через 45 секунд пропадал из «Сейчас в школе», —
 * панель показывала «у кого вкладка на переднем плане», а не «кто учится».
 *
 * Период конечный, и это вторая половина решения: вкладка, забытая на ночь,
 * отметки шлёт полчаса, а потом замолкает. Бесконечный фон означал бы «онлайн»
 * у всех, кто когда-либо не закрыл вкладку.
 */
export const PRESENCE_GRACE_MS = 30 * 60_000

/**
 * Сколько секунд отметка считается свежей.
 *
 * Было 45 секунд при отметке раз в 20. Теперь 30 минут — ровно длина льготного
 * периода: показывать надо тех, кто занимался последние полчаса, а не тех, у
 * кого вкладка сейчас поверх остальных. Экран подписан так же — «активны за
 * последние 30 минут», и подпись обязана совпадать с этим окном.
 *
 * Плата за это названа прямо: закрыл вкладку — пропадёшь не через полминуты, а
 * до получаса. Приёмка §148 изменена осознанно.
 */
export const PRESENCE_WINDOW_S = PRESENCE_GRACE_MS / 1000

/** Как часто панель перечитывает список. Только при видимой вкладке. */
export const PRESENCE_POLL_MS = 15_000

/**
 * Время последнего действия человека на платформе.
 *
 * Живёт в модуле, а не в состоянии React: слушатели вешаются один раз на
 * документ, а читает значение таймер отметки. Хранится ТОЛЬКО время — ни
 * адреса страницы, ни того, что именно человек нажал: запрет §148 «на каком
 * экране находится ребёнок» в силе, и обойти его случайно тут нечем.
 */
let lastActivityAt = 0

/** Отметить действие: клик, ввод, возвращение на вкладку. */
export function noteActivity(at: number = Date.now()): void {
  lastActivityAt = at
}

export function getLastActivityAt(): number {
  return lastActivityAt
}

/** Только для тестов: развести случаи между собой. */
export function __resetActivityForTests(): void {
  lastActivityAt = 0
}

export interface TouchDecision {
  /** Вкладка платформы скрыта. */
  hidden: boolean
  /** Когда отметились в прошлый раз. 0 — ещё ни разу. */
  lastTouchAt: number
  /** Когда человек в последний раз что-то делал на платформе. */
  lastActivityAt: number
}

/**
 * Пора ли отмечаться. Вынесено отдельно от таймеров, чтобы правило можно было
 * проверить без часов.
 *
 * Три состояния, и все три — решение, а не побочный эффект:
 *   • вкладка видна — обычный такт;
 *   • вкладка в фоне, льготный период идёт — редкий такт;
 *   • вкладка в фоне, период истёк — молчим.
 */
export function shouldTouch(now: number, state: TouchDecision): boolean {
  const sinceTouch = now - state.lastTouchAt
  if (!state.hidden) return sinceTouch >= PRESENCE_TOUCH_MS
  // Фон: сначала право быть здесь, потом уже частота.
  if (now - state.lastActivityAt >= PRESENCE_GRACE_MS) return false
  return sinceTouch >= PRESENCE_BACKGROUND_TOUCH_MS
}

export interface PresencePerson {
  profileId: string
  role: string
}

/** Разбор ответа `school_presence_online()`. Битые строки отбрасываются. */
export function parseOnline(raw: unknown): PresencePerson[] {
  if (!Array.isArray(raw)) return []
  const seen = new Map<string, PresencePerson>()
  for (const row of raw) {
    const profileId = String((row as any)?.profile_id ?? '').trim()
    if (!profileId || seen.has(profileId)) continue
    seen.set(profileId, { profileId, role: String((row as any)?.role ?? '') })
  }
  return [...seen.values()]
}

/**
 * Сравнение составов. Нужно, чтобы опрос раз в 15 секунд не перерисовывал
 * список, когда в нём ничего не изменилось: у одних и тех же людей меняется
 * только `seen_at`, а он на экран не идёт.
 */
export function samePeople(a: PresencePerson[], b: PresencePerson[]): boolean {
  if (a.length !== b.length) return false
  return a.every((person, i) => person.profileId === b[i]?.profileId && person.role === b[i]?.role)
}
