/**
 * По какому году считаем сейчас. Подпись в интерфейсе — «по шкале ЕГЭ-<год>»
 * (решение владельца 02.10, п. 5), поэтому год берётся отсюда же.
 */
export const ACTIVE_EGE_YEAR: Readonly<Record<EgeSubject, number>> = {
  math: 2026,
  physics: 2026,
}

/** Порядок предметов в переключателе (как в макете: математика, потом физика). */
export const EGE_SUBJECT_ORDER: readonly EgeSubject[] = ['math', 'physics']

export function isEgeSubject(v: unknown): v is EgeSubject {
  return v === 'math' || v === 'physics'
}

/** Действующая запись предмета; null — предмета нет (ОГЭ, другие предметы). */
export function activeSpec(subject: string): EgeSpec | null {
  if (!isEgeSubject(subject)) return null
  return EGE_SPECS[`${subject}:${ACTIVE_EGE_YEAR[subject]}`] ?? null
}

export function maxPrimary(spec: EgeSpec): number {
  return spec.maxPoints.reduce((s, m) => s + m, 0)
}

/** Номера первой части: 1…part1Last. */
export function part1Numbers(spec: EgeSpec): number[] {
  return Array.from({ length: spec.part1Last }, (_, i) => i + 1)
}

export function maxOf(spec: EgeSpec, n: number): number {
  return spec.maxPoints[n - 1] ?? 0
}

/**
 * Тестовый балл по первичному. Прогноз даёт ДРОБНЫЙ первичный (9,4 —
 * ожидание, а не итог экзамена), поэтому между соседними точками таблицы —
 * линейная интерполяция: 9,4 → 52 + 0,4 × (58 − 52) = 54,4. На целых точках
 * совпадает с таблицей. Вне [0, максимум] — прижимается к краю.
 */
export function toTestScore(spec: EgeSpec, primary: number): number {
  const top = spec.scale.length - 1
  if (!Number.isFinite(primary) || primary <= 0) return spec.scale[0]
  if (primary >= top) return spec.scale[top]
  const lo = Math.floor(primary)
  const frac = primary - lo
  return spec.scale[lo] + frac * (spec.scale[lo + 1] - spec.scale[lo])
}

