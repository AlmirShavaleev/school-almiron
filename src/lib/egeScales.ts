/**
 * §255. Структура КИМ ЕГЭ и шкалы перевода — ДАННЫМИ, а не кодом.
 *
 * Запись = предмет + год: сколько заданий, сколько баллов за каждое, где
 * кончается первая часть, таблица перевода первичный → тестовый и порог.
 * Прогноз (`egeForecast.ts`) и карточка главной читают только эту запись,
 * поэтому новый год (профильная математика-2027: 20 заданий, 33 балла,
 * перенумерация) добавляется ОДНОЙ записью в `EGE_SPECS` и сменой года в
 * `ACTIVE_EGE_YEAR` — без правки формул.
 *
 * Источники (сверено оркестратором 02.10.2026):
 *   * разбалловка по заданиям — спецификация ФИПИ 2026;
 *   * перевод первичный → тестовый — таблицы Рособрнадзора 2026
 *     (obrnadzor.gov.ru, утверждены после досрочного этапа, 20.04.2026).
 *
 * Почему 2026, а не 2027: 11А сдаёт в 2027, но шкалы 2027 нет, а курсы
 * размечены по нумерации 2026 («№13 — тригонометрические уравнения»). Физика-2027
 * без изменений; математику-2027 добавим записью, когда выйдет шкала.
 *
 * Тест `egeScales.test.ts` стережёт: сумма баллов по номерам = максимум
 * первичного, таблица монотонна, 0 → 0, максимум → 100.
 */

export type EgeSubject = 'math' | 'physics'

export interface EgeSpec {
  subject:  EgeSubject
  year:     number
  /** Подпись предмета в переключателе. */
  label:    string
  /** maxPoints[i] — максимум за задание №(i + 1). Длина — число заданий. */
  maxPoints: readonly number[]
  /** Номер последнего задания первой части (включительно). */
  part1Last: number
  /** scale[первичный] = тестовый; длина = максимум первичного + 1. */
  scale:    readonly number[]
  /** Минимальный тестовый балл (порог), отметка на шкале. */
  threshold: number
}

