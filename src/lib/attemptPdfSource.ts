/**
 * §206. Слепок того, что аннотатор сейчас показывает на экране, — то, из чего
 * собирается скачиваемый PDF.
 *
 * Отдельный модуль ради одного: `SubmissionReviewer` (1563 строки) ничего не
 * знает про экспорт, а модуль отрисовки ничего не знает про аннотатор. Между
 * ними — этот словарь типов, который тянет за собой только `pdfjs` в виде
 * типа документа.
 *
 * Важно, что экспортируется именно ЭКРАН: у преподавателя это может быть
 * неопубликованный черновик пометок (он скачивает своё), у ученика — только
 * опубликованные, потому что больше ему аннотатор и не показывает.
 */

import type { PDFDocumentProxy } from 'pdfjs-dist'
import type { Quarter } from './pageRotation'

export interface AttemptExportSurface {
  /** Сквозной номер страницы: файл за файлом, страница за страницей. */
  globalPage: number
  kind: 'pdf' | 'image'
  /** Подписанная ссылка на файл — для картинок; PDF уже открыт движком. */
  url: string
  /** Номер страницы внутри файла (у картинки всегда 1). */
  page: number
  /** Ширина к высоте — запасной вариант, если размер страницы иначе не узнать. */
  ratio: number
  /**
   * §211. На сколько четвертей по часовой стрелке страницу довернули на
   * экране. В файл она обязана лечь ровно так же: преподаватель выправил
   * боком снятый лист у себя — значит ученик получит его выправленным, а не
   * узнает о повороте, только открыв файл.
   */
  quarter: Quarter
  /** Уже загруженный документ pdfjs; у картинок null. */
  pdf: PDFDocumentProxy | null
}

export interface AttemptExportRegion {
  /**
   * Номер рамки. Он же номер пункта в списке замечаний на последней странице:
   * без этой связки рамка на странице 4 и текст в конце читались бы как два
   * разных документа.
   */
  number: number
  globalPage: number
  /**
   * Доли страницы, 0..1 — ровно те числа, которыми рамка рисуется на экране.
   * §211: у повёрнутой страницы это доли ПОВЁРНУТОГО листа, потому что и в
   * файл она ложится повёрнутой.
   */
  rect: { x: number; y: number; w: number; h: number }
  categoryLabel: string
  color: string
  text: string
  /**
   * §209. Задание, к которому привязано замечание. Нужно последней странице:
   * разбор в файле печатает замечания под теми же заданиями, что экран.
   */
  taskNo?: string | null
}

export interface AttemptExportSnapshot {
  surfaces: AttemptExportSurface[]
  /** В порядке списка комментариев; номера уже проставлены. */
  regions: AttemptExportRegion[]
  /**
   * §209.1. Все ли файлы работы уже открыты.
   *
   * Пока PDF читается движком, `surfaces` содержит только фотографии — и
   * слепок в этот момент выглядит совершенно исправным, просто в нём нет
   * половины работы. Кнопка «Скачать PDF» обязана на это смотреть: иначе
   * преподаватель, нажавший сразу после открытия, получит файл без страниц
   * PDF и без единой ошибки. Такую пропажу замечает уже ученик.
   */
  ready: boolean
}

/** Доступ к слепку снаружи аннотатора. */
export type AttemptExportSourceRef = { current: (() => AttemptExportSnapshot) | null }
