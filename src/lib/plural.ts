/**
 * Склонение существительного при числительном.
 *
 * Одно место на всё приложение. Жила эта функция в `courseDelete.ts` — там она
 * и появилась, для диалога удаления курса, — но оттуда её нельзя звать из
 * кабинета ученика: `courseDelete` тянет `supabase` и всю механику удаления, и
 * ради одного слова в чанк страницы уехал бы весь модуль. Поэтому определение
 * переехало сюда, а `courseDelete` его реэкспортирует: вторая копия правил
 * русского языка нам не нужна.
 *
 * Правило: 11–14 всегда «много» (одиннадцать тем, четырнадцать тем), иначе
 * решает последняя цифра. Проверка на 11–14 обязана идти ПЕРВОЙ — иначе 11
 * получит форму от единицы («11 тема»), а 12–14 от двойки («12 темы»).
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const mod100 = n % 100
  if (mod100 >= 11 && mod100 <= 14) return many
  switch (n % 10) {
    case 1: return one
    case 2:
    case 3:
    case 4: return few
    default: return many
  }
}

/** «2 темы», «5 тем» — число и правильная форма слова одной строкой. */
export function pluralTopics(n: number): string {
  return `${n} ${plural(n, 'тема', 'темы', 'тем')}`
}
