/**
 * §244. Класс на странице «Курсы»: по какому ключу две копии разных шаблонов
 * считаются одним классом.
 *
 * Класс в базе не хранится: у каждой копии шаблона (курса группы) есть только
 * своё название. «Математика ЕГЭ. 1 часть — 11А» и «Физика ЕГЭ 11А класс» —
 * это один 11А, если отбросить общую с шаблоном часть (`copyDisplayTitle`) и
 * сравнить остаток «по смыслу», а не посимвольно:
 *
 *  - регистр не важен, «ё» = «е»;
 *  - слово «класс» не важно: «11А класс» = «11А»;
 *  - порядок слов не важен: «2026-2027 Ученики» = «Ученики 2026–2027»;
 *  - тире любой длины — одно тире: «2026–2027» = «2026-2027»;
 *  - цифра и буква литеры склеиваются: «11 А» = «11-А» = «11А»;
 *  - латинская литера, похожая на русскую, — русская: «11A» (латиница) = «11А».
 *
 * Функции чистые, про запросы и курсы ничего не знают.
 */

/** Латинские буквы, которые на письме не отличить от русских. */
const LATIN_LOOKALIKE: Record<string, string> = {
  a: 'а', b: 'в', c: 'с', e: 'е', h: 'н', k: 'к', m: 'м', o: 'о', p: 'р', t: 'т', x: 'х', y: 'у',
}

/** Слова, которые на класс не влияют. */
const NOISE = new Set(['класс', '-'])

/** Ключ класса: одинаковый у всех написаний одного класса. */
export function classKey(name: string): string {
  let s = (name ?? '').trim().toLocaleLowerCase('ru').replace(/ё/g, 'е')
  s = s.replace(/[‐‑‒–—―−]/g, '-')
  // «11 А», «11-А» → «11а». Буква должна быть одна — «10 апреля» не трогаем.
  s = s.replace(/(\d)\s*-?\s*([a-zа-я])(?![a-zа-я])/g, '$1$2')

  const words = s
    .split(/[\s,.;:()«»"'·/]+/)
    .filter(Boolean)
    .map(w => (/^\d+[a-z]$/.test(w) ? w.slice(0, -1) + (LATIN_LOOKALIKE[w.slice(-1)] ?? w.slice(-1)) : w))
    .filter(w => !NOISE.has(w))

  // Название из одного «класс» — ключом остаётся оно само, а не пустота:
  // пустой ключ склеил бы в один класс всё, что сократилось до шума.
  if (words.length === 0) return s
  return [...words].sort().join(' ')
}

/**
 * Какое написание показывать у класса: самое частое, при равенстве — первое
 * встреченное. «11А», «11А», «11А класс» → «11А».
 */
export function pickDisplayName(names: string[]): string {
  // Map помнит порядок первой вставки — это и есть «первое встреченное».
  const counts = new Map<string, number>()
  for (const raw of names) {
    const name = raw.trim()
    if (name) counts.set(name, (counts.get(name) ?? 0) + 1)
  }
  let best = ''
  let bestCount = 0
  for (const [name, n] of counts) {
    if (n > bestCount) {
      best = name
      bestCount = n
    }
  }
  return best
}
