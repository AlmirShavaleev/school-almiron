import { beforeAll,afterAll,describe,it,expect } from 'vitest'
import { PGlite } from '@electric-sql/pglite'
import { readFileSync } from 'node:fs'
const db=new PGlite(),admin='00000000-0000-4000-8000-000000000001',student='00000000-0000-4000-8000-000000000002',payment='00000000-0000-4000-8000-000000000003'
beforeAll(async()=>{
 await db.exec(`create role anon;create role authenticated;create role service_role;
 create table profiles(id uuid primary key,email text,role text);
 create function public.is_admin_or_owner() returns boolean language sql as $$select false$$;
 create table telegram_connections(profile_id uuid,is_enabled boolean,disconnected_at timestamptz);
 create table subscription_payments(id uuid primary key,status text);
 create table subscription_log(id bigint generated by default as identity,payment_id uuid,subscription_id uuid,event text,details jsonb);
 create schema vault;create table vault.decrypted_secrets(name text,decrypted_secret text);
 create schema net;create function net.http_post(url text,headers jsonb,body jsonb,timeout_milliseconds int)returns bigint language sql as $$select 1::bigint$$;
 create schema cron;create function cron.schedule(text,text,text)returns bigint language sql as $$select 1::bigint$$;
 insert into profiles values('${admin}','owner@almiron.ru','admin'),('${student}','student@test','student');
 insert into telegram_connections values('${admin}',true,null);
 insert into subscription_payments values('${payment}','succeeded');`)
 await db.exec(readFileSync(`${process.cwd()}/supabase/migrations/20261112133113_admin_payment_telegram_notifications.sql`,'utf8'))
},20000)
afterAll(()=>db.close())
describe('очередь успешных оплат для администратора',()=>{
 it('не рассылает исторические оплаты, но ставит новую подтверждённую оплату один раз',async()=>{
  expect((await db.query('select * from admin_payment_notifications')).rows).toHaveLength(0)
  await db.exec(`insert into subscription_log(payment_id,event)values('${payment}','payment_succeeded'),('${payment}','payment_succeeded');`)
  const {rows}=await db.query<{recipient_profile_id:string}>('select recipient_profile_id from admin_payment_notifications')
  expect(rows).toHaveLength(1);expect(rows[0].recipient_profile_id).toBe(admin)
  await db.exec(`insert into subscription_log(payment_id,event)values('${payment}','payment_canceled')`)
  expect((await db.query('select * from admin_payment_notifications')).rows).toHaveLength(1)
 })
 it('захват атомарный, повторно занятая запись не выдаётся',async()=>{
  const first=await db.query('select * from claim_admin_payment_notifications(10)');expect(first.rows).toHaveLength(1)
  expect((await db.query('select * from claim_admin_payment_notifications(10)')).rows).toHaveLength(0)
 })
 it('ученик и anon не могут запускать очередь или читать получателя',async()=>{
  await db.exec('set role authenticated')
  await expect(db.query('select * from claim_admin_payment_notifications(10)')).rejects.toThrow(/permission denied/)
  expect((await db.query('select * from admin_payment_notifications')).rows).toHaveLength(0)
  await db.exec('reset role;set role anon')
  await expect(db.query('select * from claim_admin_payment_notifications(10)')).rejects.toThrow(/permission denied/)
  await db.exec('reset role')
 })
})
