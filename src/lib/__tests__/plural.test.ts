import { describe, expect, it } from 'vitest'
import { plural, pluralTopics } from '@/lib/plural'
import { plural as pluralFromCourseDelete } from '@/lib/courseDelete'

/**
 * Склонение существительного при числительном.
 *
 * Поводом стало обращение ученика через «Сообщить о проблеме»: на странице
 * курса стояло «2 тем» вместо «2 темы». Прежний код выбирал из ДВУХ форм
 * («одна» против «все остальные») — такой развилки для русского языка не
 * хватает в принципе.
 *
 * Набор чисел ниже — из приёмки задачи, и он подобран не случайно: 21 и 111
 * ловят потерю правила «смотри последнюю цифру», а 11–14 — обратную ошибку,
 * когда последнюю цифру смотрят ВМЕСТО исключения на второй десяток.
 */

describe('plural', () => {
  it('единица — 1, 21, 101', () => {
    expect(plural(1, 'тема', 'темы', 'тем')).toBe('тема')
    expect(plural(21, 'тема', 'темы', 'тем')).toBe('тема')
    expect(plural(101, 'тема', 'темы', 'тем')).toBe('тема')
  })

  it('двойка-четвёрка — 2, 22, 25 уже нет', () => {
    expect(plural(2, 'тема', 'темы', 'тем')).toBe('темы')
    expect(plural(3, 'тема', 'темы', 'тем')).toBe('темы')
    expect(plural(4, 'тема', 'темы', 'тем')).toBe('темы')
    expect(plural(22, 'тема', 'темы', 'тем')).toBe('темы')
  })

  it('много — 5, 25, 111', () => {
    expect(plural(5, 'тема', 'темы', 'тем')).toBe('тем')
    expect(plural(25, 'тема', 'темы', 'тем')).toBe('тем')
    // 111: последняя цифра единица, но второй десяток сильнее.
    expect(plural(111, 'тема', 'темы', 'тем')).toBe('тем')
  })

  it('второй десяток — исключение целиком, 11–14 всегда «много»', () => {
    // Если проверку на 11–14 убрать или поставить ПОСЛЕ разбора последней
    // цифры, здесь появятся «11 тема» и «12 темы».
    for (const n of [11, 12, 13, 14]) {
      expect(plural(n, 'тема', 'темы', 'тем')).toBe('тем')
    }
    // Соседи второго десятка правилу подчиняются как обычно.
    expect(plural(10, 'тема', 'темы', 'тем')).toBe('тем')
    expect(plural(15, 'тема', 'темы', 'тем')).toBe('тем')
  })

  it('ноль — «много», как и положено', () => {
    expect(plural(0, 'тема', 'темы', 'тем')).toBe('тем')
  })

  it('работает не только на темах', () => {
    expect(plural(2, 'ученик', 'ученика', 'учеников')).toBe('ученика')
    expect(plural(5, 'ученик', 'ученика', 'учеников')).toBe('учеников')
  })
})

describe('pluralTopics', () => {
  it('склеивает число и правильную форму', () => {
    expect(pluralTopics(1)).toBe('1 тема')
    expect(pluralTopics(2)).toBe('2 темы')
    expect(pluralTopics(5)).toBe('5 тем')
    expect(pluralTopics(21)).toBe('21 тема')
    expect(pluralTopics(22)).toBe('22 темы')
    expect(pluralTopics(25)).toBe('25 тем')
    expect(pluralTopics(111)).toBe('111 тем')
  })

  it('то самое «2 темы», с которого началась задача', () => {
    expect(pluralTopics(2)).not.toBe('2 тем')
  })
})

describe('копия не заведена', () => {
  it('courseDelete отдаёт ТУ ЖЕ функцию, а не свою', () => {
    // Реэкспорт, а не второй экземпляр: две копии правил русского языка
    // разъехались бы с первой же правкой (урок §21/§29 про копии условий).
    expect(pluralFromCourseDelete).toBe(plural)
  })
})
