import { describe, expect, it } from 'vitest'
import { shortLockLabel } from '@/lib/courseScreen'

// Подпись замка на плитке урока — коротко, номером урока (владелец 15.10).
describe('shortLockLabel', () => {
  const no = new Map([['Пропорции. Во сколько раз изменится', 2]])

  it('«после урока «название»» → «после урока N»', () => {
    expect(shortLockLabel('Откроется после урока «Пропорции. Во сколько раз изменится»', no))
      .toBe('Откроется после урока 2')
  })

  it('с датой — дата остаётся', () => {
    expect(shortLockLabel('Откроется после урока «Пропорции. Во сколько раз изменится» или 12 октября', no))
      .toBe('Откроется после урока 2 или 12 октября')
  })

  it('урок из другого раздела или без номера — подпись как была', () => {
    expect(shortLockLabel('Откроется после урока «Векторы»', no)).toBe('Откроется после урока «Векторы»')
    expect(shortLockLabel('Доступно по подписке', no)).toBe('Доступно по подписке')
  })
})
