import { describe, expect, it } from 'vitest'
import { classKey, pickDisplayName } from '@/lib/classKey'

/** §244. Один класс — один ключ, как бы его ни написали в названии копии. */
describe('classKey — нормализация имени класса', () => {
  const same = (a: string, b: string) => expect(classKey(a)).toBe(classKey(b))
  const differ = (a: string, b: string) => expect(classKey(a)).not.toBe(classKey(b))

  it('слово «класс» не важно', () => {
    same('11А класс', '11А')
    same('класс 11А', '11А')
  })

  it('регистр не важен', () => {
    same('11а', '11А')
    same('УЧЕНИКИ 2026-2027', 'ученики 2026-2027')
  })

  it('порядок слов не важен', () => {
    same('2026-2027 Ученики', 'Ученики 2026-2027')
  })

  it('длинное и короткое тире — одно и то же', () => {
    same('Ученики 2026–2027', 'Ученики 2026-2027')
    same('Ученики 2026—2027', '2026-2027 Ученики')
  })

  it('«11 А», «11-А» и «11А» — один класс', () => {
    same('11 А', '11А')
    same('11-А класс', '11А')
  })

  it('латинская «A» в литере — то же, что русская «А»', () => {
    same('11A', '11А')
    same('10B', '10В')
  })

  it('«ё» и «е» не различаются', () => {
    same('Ёлки 5', 'елки 5')
  })

  it('разные классы остаются разными', () => {
    differ('11А', '11Б')
    differ('11А', '10А')
    differ('Ученики 2026-2027', 'Ученики 2025-2026')
  })

  it('буква после числа склеивается, только если она одна: «10 апреля» не трогаем', () => {
    differ('10 апреля', '10а преля')
  })

  it('название из одного слова «класс» не превращается в пустой ключ', () => {
    expect(classKey('класс')).toBe('класс')
    differ('класс', '')
  })
})

describe('pickDisplayName — какое написание показать', () => {
  it('самое частое', () => {
    expect(pickDisplayName(['11А класс', '11А', '11А'])).toBe('11А')
  })

  it('при равенстве — первое встреченное', () => {
    expect(pickDisplayName(['11А класс', '11А'])).toBe('11А класс')
    expect(pickDisplayName(['B', 'A', 'A', 'B'])).toBe('B')
  })

  it('пустые строки не считаются', () => {
    expect(pickDisplayName(['', '  ', '10А'])).toBe('10А')
    expect(pickDisplayName([])).toBe('')
  })
})
