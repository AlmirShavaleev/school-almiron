import { describe, expect, it } from 'vitest'
import { copyDisplayTitle } from '@/lib/courseDisplayName'

/**
 * §114. Короткое имя копии в списке. Каждый случай здесь — из условий владельца:
 * правило полезно ровно до тех пор, пока не начинает обрезать смысл.
 */
describe('copyDisplayTitle', () => {
  it('обычный случай: от копии остаётся различающийся хвост', () => {
    expect(copyDisplayTitle(
      'Математика ЕГЭ. 1 часть + джентльменский набор — 11А',
      'Математика ЕГЭ. 1 часть + джентльменский набор — Шаблон',
    )).toBe('11А')
  })

  it('хвост из нескольких слов остаётся целиком', () => {
    expect(copyDisplayTitle('Физика ЕГЭ 11А класс', 'Физика ЕГЭ Шаблон')).toBe('11А класс')
  })

  it('висящее тире на стыке срезается', () => {
    expect(copyDisplayTitle('Курс — 11Б', 'Курс — Шаблон')).toBe('11Б')
    expect(copyDisplayTitle('Курс : 11Б', 'Курс : Шаблон')).toBe('11Б')
    expect(copyDisplayTitle('Курс · 11Б', 'Курс · Шаблон')).toBe('11Б')
  })

  it('общего префикса нет — показываем полное название, без выдумок', () => {
    expect(copyDisplayTitle('Подготовка к ОГЭ 9Б', 'Физика ЕГЭ Шаблон'))
      .toBe('Подготовка к ОГЭ 9Б')
  })

  /** Обрезка по словам, а не по символам: «1 ч» вместо «1 часть» — хуже длинного. */
  it('срез не приходится на середину слова', () => {
    // «часть» и «частично» начинаются одинаково, но это разные слова.
    expect(copyDisplayTitle('Матанализ частично 11А', 'Матанализ часть 1'))
      .toBe('частично 11А')
  })

  it('префикс совпал целиком — остатка нет, показываем полное', () => {
    expect(copyDisplayTitle('Физика ЕГЭ Шаблон', 'Физика ЕГЭ Шаблон')).toBe('Физика ЕГЭ Шаблон')
  })

  it('остаток короче двух символов — полное название', () => {
    // «А» в списке не опознать; «11А» — можно.
    expect(copyDisplayTitle('Физика ЕГЭ А', 'Физика ЕГЭ Шаблон')).toBe('Физика ЕГЭ А')
    expect(copyDisplayTitle('Физика ЕГЭ 11', 'Физика ЕГЭ Шаблон')).toBe('11')
  })

  it('остаток из одних разделителей не оставляет пустоты', () => {
    expect(copyDisplayTitle('Курс —', 'Курс Шаблон')).toBe('Курс —')
  })

  it('шаблона нет — сокращать не от чего', () => {
    expect(copyDisplayTitle('Физика ЕГЭ 11А', null)).toBe('Физика ЕГЭ 11А')
    expect(copyDisplayTitle('Физика ЕГЭ 11А', undefined)).toBe('Физика ЕГЭ 11А')
  })

  it('регистр общей части не мешает', () => {
    expect(copyDisplayTitle('физика ЕГЭ 11А класс', 'Физика ЕГЭ Шаблон')).toBe('11А класс')
  })

  it('лишние пробелы не ломают счёт слов', () => {
    expect(copyDisplayTitle('Физика   ЕГЭ   11А', 'Физика ЕГЭ Шаблон')).toBe('11А')
  })

  it('пустое название остаётся пустым, а не превращается в мусор', () => {
    expect(copyDisplayTitle('', 'Физика ЕГЭ Шаблон')).toBe('')
  })
})
