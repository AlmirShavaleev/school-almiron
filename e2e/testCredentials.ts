// §160: пароль демо-учёток раньше был захардкожен в открытом виде в каждом
// e2e-файле по отдельности — тот же литерал, что утёк в LoginPage.tsx,
// seed-users.mjs и README.md. Одно место, значение приходит только из
// окружения; нет значения — тест падает с понятным текстом, а не тихо
// логинится куда-то с угаданным паролем.
export const DEMO_PASSWORD = (() => {
  const pwd = process.env.SEED_PASSWORD
  if (!pwd) {
    throw new Error(
      'SEED_PASSWORD не задан. Пароль демо-учёток для e2e больше не хранится в коде — передайте его переменной окружения (тот же пароль, что и scripts/seed-users.mjs).',
    )
  }
  return pwd
})()
