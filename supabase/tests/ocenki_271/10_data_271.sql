-- Значение первого столбца первой строки (или ошибка); сколько строк (или ошибка).
create or replace function public.probe_val(p_sql text) returns text
language plpgsql security invoker as $$
declare v text;
begin
  execute p_sql into v;
  return coalesce(v, 'null');
exception when others then
  return 'ERR ' || sqlstate || ': ' || left(sqlerrm, 90);
end $$;
create or replace function public.probe_count(p_sql text) returns text
language plpgsql security invoker as $$
declare n bigint;
begin
  execute 'select count(*) from (' || p_sql || ') q' into n;
  return 'rows=' || n;
exception when others then
  return 'ERR ' || sqlstate || ': ' || left(sqlerrm, 90);
end $$;
grant execute on function public.probe_val(text), public.probe_count(text) to authenticated, anon;
