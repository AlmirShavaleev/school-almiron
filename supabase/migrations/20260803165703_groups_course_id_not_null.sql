-- Последний шаг закона «один курс = одна группа»: группа без курса невозможна.
--
-- Ставится только сейчас, а не вместе с unique(course_id) в §61: до этой
-- сессии GroupModal умел создавать группу без курса (`course_id: courseId ||
-- null`, курс в форме не был обязателен), и NOT NULL превратил бы живое
-- действие интерфейса в сырую ошибку базы. Создание групп из интерфейса
-- убрано, курс в форме стал обязательным — препятствие снято.
--
-- Взяться безхозной группе теперь неоткуда: курс рождает свою группу
-- триггером courses_ensure_group, удаление курса уносит её каскадом
-- (FK переведён с SET NULL в §61), а вторую не пустит unique(course_id).
-- Вместе с NOT NULL закон становится несжимаемым: ровно одна группа на курс,
-- ни одной сверх и ни одной в стороне.

alter table public.groups alter column course_id set not null;

comment on column public.groups.course_id is
  'Курс группы. NOT NULL: один курс = одна группа, группа вне курса не существует (§64).';

