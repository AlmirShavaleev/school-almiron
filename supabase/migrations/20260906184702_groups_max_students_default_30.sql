-- Умолчание вместимости группы: 15 → 30.
--
-- Владелец упёрся в лимит на живой группе; текущие значения подняты вручную,
-- но каждая новая группа заводилась снова с 15.
--
-- Почему правка именно умолчания колонки, а не кода: группы из интерфейса
-- больше не создаются (§61, «один курс = одна группа») — новую заводит триггер
-- `courses_ensure_group`, а он вставляет только `course_id`, `name` и
-- `teacher_id`. Значит `max_students` у каждой новой группы приходит ровно из
-- умолчания этой колонки, и другого источника у него нет.
--
-- Изменение добавляющее: существующие строки не трогаются, старый код
-- продолжает работать — он это значение только читает и явно передаёт при
-- распределении (`distribute_student_courses`, `distribute_join_request`
-- требуют max_students в запросе и умолчанием не пользуются).
alter table public.groups alter column max_students set default 30;
