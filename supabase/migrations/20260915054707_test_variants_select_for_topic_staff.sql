-- §177 (применено оркестратором 15.09, версия 20260915054707). Персонал курса
-- видит варианты-носители задач к уроку своих тем.
--
-- tv_select отдаёт преподавателю только created_by = auth.uid(). Носитель
-- задач к уроку (test_variants.topic_id, §164) создаётся тем, кто прикрепил
-- задачи в каркасе, и синхронизацией §172 — то есть у преподавателя класса
-- created_by чужой, и матрица «Материалы» (§177), читающая test_variants
-- напрямую, показала бы ✗ при живых задачах. Политика добавляющая: только
-- SELECT, только строки с topic_id, только персонал курса этой темы —
-- через course_is_staff (CLAUDE.md: любая проверка «персонал ли» — только
-- через неё). Обычные варианты (topic_id is null) не затрагиваются.
-- Проба 15.09: владелец видит 4 носителя, посторонний преподаватель 0,
-- ученик — только свой выданный.

create policy tv_select_topic_staff on public.test_variants
  for select
  using (
    topic_id is not null
    and public.course_is_staff(public.course_of_topic(topic_id))
  );
