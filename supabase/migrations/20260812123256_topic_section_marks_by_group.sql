-- Отметка переезжает с рубрики на ГРУППУ рубрик (§121: «Теория», «Урок»,
-- «Домашнее задание»). Правка §122 по живому просмотру владельца 12.08.
--
-- Почему меняем схему, а не собираем группу из рубрик в коде: кнопка группы,
-- проставляющая отметки всем её рубрикам разом, оставила бы в базе записи,
-- которых человек по отдельности не ставил. Дальше любое изменение состава
-- группы (а он уже менялся — §100, §121) сдвигало бы завершённость задним
-- числом: вчера тема была закрыта, сегодня в группу добавили рубрику — и она
-- «раззавершилась». Одна отметка = одно действие человека.
--
-- Группа `homework` сюда не пишется никогда — она засчитывается принятой
-- работой, как и раньше раздел `homework`. Тестирование в группы §121 не
-- входит вовсе, поэтому и в отметках его нет.
--
-- Строк в таблице ноль (заведена сегодня, §122), поэтому переносить нечего;
-- удаление ниже — честная страховка на случай, если что-то успело появиться
-- между миграциями: старые порубричные значения в новом CHECK всё равно
-- недопустимы, а два способа отметить одно и то же разъедутся.
delete from public.topic_section_marks;

alter table public.topic_section_marks
  drop constraint if exists topic_section_marks_section_check;

alter table public.topic_section_marks
  rename column section to group_key;

alter table public.topic_section_marks
  add constraint topic_section_marks_group_key_check
  check (group_key in ('theory', 'lesson'));

comment on table public.topic_section_marks is
  'Самоотметки ученика по ГРУППАМ рубрик темы (theory / lesson), §121. «Отметил сам», не факт. Группа homework сюда не пишется — она засчитывается принятой работой. Снятие отметки = удаление строки, UPDATE не предусмотрен.';

comment on column public.topic_section_marks.group_key is
  'Ключ группы рубрик из TOPIC_SECTION_GROUPS. Не рубрика: одна отметка = одно действие человека, иначе изменение состава группы двигало бы завершённость задним числом.';
