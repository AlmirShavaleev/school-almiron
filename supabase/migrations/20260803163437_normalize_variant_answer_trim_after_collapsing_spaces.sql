-- Порядок операций съедал 72 задачи, у которых эталон — обычное число.
--
-- Было: trim(raw) → replace(',', '.') → \s+ схлопнуть в ' '.
-- Неразрывный пробел (U+00A0) trim не берёт, он ASCII-only. Зато следующим
-- шагом регулярка \s+ считает его пробелом и заменяет на обычный — уже ПОСЛЕ
-- того, как trim отработал. В итоге «<nbsp>6» превращается в « 6» с ведущим
-- пробелом, проверка на число не проходит, и задача уходит из автопроверки в
-- ветку «не проверено»: балл теряется молча (§62).
--
-- Стало: схлопнуть пробелы, потом обрезать края. Порядок — единственное, что
-- меняется; сам набор преобразований прежний.
--
-- Индексов и генерируемых колонок на функции нет (проверено), поэтому смена
-- поведения IMMUTABLE-функции ничего не разрушает.

CREATE OR REPLACE FUNCTION public.normalize_variant_answer(raw text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE PARALLEL SAFE STRICT
 SET search_path TO 'public'
AS $function$
  SELECT lower(
    btrim(
      regexp_replace(
        replace(raw, ',', '.'),
        '\s+', ' ', 'g'
      )
    )
  );
$function$;

comment on function public.normalize_variant_answer(text) is
  'Нормализация ответа: запятая→точка, пробелы схлопнуть, обрезать края, в нижний регистр. Обрезка ИМЕННО после схлопывания — иначе неразрывный пробел выживает.';
