-- §214 (board/066). Пятый вердикт строки таблицы проверки: 'unsolved'.
--
-- ЗАЧЕМ. «Не сверено» тащило два разных смысла: «ИИ не смогла сверить — надо
-- посмотреть глазами» и «ученик не решал — надо садиться и делать». Для
-- преподавателя это разные действия, для ученика — разные комментарии, а
-- переписывание комментария (§213) физически не может отличить одно от
-- другого, пока значение одно: владелец поймал это на живой работе, где
-- задания 6 и 9 ученик не делал, а комментарий сообщил, что они «выполнены с
-- ошибками».
--
-- ПРОВЕРКА РАСШИРЯЕТСЯ, А НЕ СУЖАЕТСЯ. Все существующие строки проходят новое
-- ограничение, и старый клиент, который знает только четыре значения,
-- продолжает работать без изменений. Поэтому порядок обязателен: СНАЧАЛА эта
-- миграция, ПОТОМ выкладка кода — иначе первая же запись нового значения
-- упадёт на CHECK.
--
-- ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ у колонки ('unchecked') не трогаем: новая строка,
-- добавленная руками, по-прежнему «не сверена», и это правильно — «не решено»
-- ставит человек, а не умолчание.
--
-- СТАРЫЕ СТРОКИ НЕ ПЕРЕПИСЫВАЕМ. Ни одного UPDATE: где сейчас «не сверено»,
-- там оно и останется, пока преподаватель не поменяет руками. На проде это
-- 7 строк из 161 в 13 работах — по заметкам ИИ все они на самом деле «не
-- решено», но решать это за человека мы не будем.
--
-- ФУНКЦИЮ topic_homework_review_tasks_seed НЕ МЕНЯЕМ. Это единственное место
-- в базе, где четыре значения перечислены поимённо, и перечислены они там про
-- ответ МОДЕЛИ: ИИ по-прежнему ставит только 'unchecked', и учить её
-- различать — отдельная работа (после §220). Перенос находок остаётся
-- 'unchecked' → 'unchecked'.

alter table public.topic_homework_review_tasks
  drop constraint if exists topic_homework_review_tasks_verdict_check;

alter table public.topic_homework_review_tasks
  add constraint topic_homework_review_tasks_verdict_check
  check (verdict = any (array['correct', 'wrong', 'partial', 'unchecked', 'unsolved']));

comment on column public.topic_homework_review_tasks.verdict is
  'Вердикт преподавателя по заданию: correct | wrong | partial | unchecked | unsolved. '
  '§214: unchecked — не сверено (надо посмотреть глазами), unsolved — не решено '
  '(ученик задание не делал). ИИ ставит только первые четыре.';
